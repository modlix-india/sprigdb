/// Blocked reads served by another connection's write, and timeouts.
#[ignore = "live: needs SPRIG_TEST_REDIS_REF; tools/live/README.md"]
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn blocking_reads_match_redis() {
    let Some(refaddr) = var("SPRIG_TEST_REDIS_REF") else {
        eprintln!("SPRIG_TEST_REDIS_REF not set: skipped");
        panic!("live test run without its environment: see tools/live/README.md");
    };
    let (addr, u, pw) = sprig_server().await;
    let a = |s: &str| split(s);
    let mut t = Tally::default();
    for proto in ["2", "3"] {
        let mut results: Vec<Vec<(V, bool)>> = Vec::new();
        for (target, login) in [
            (addr.as_str(), Some((u.as_str(), pw.as_str()))),
            (refaddr.as_str(), None),
        ] {
            let mut r = Conn::open(target, login).await;
            let mut w = Conn::open(target, login).await;
            r.call(&a(&format!("HELLO {proto}"))).await;
            w.call(&a("FLUSHALL")).await;
            let mut out = Vec::new();
            let mut step = |v: V, slow: bool| out.push((v, slow));
            // 1. XREAD BLOCK on a missing key, served by an XADD.
            r.send(&a("XREAD BLOCK 5000 STREAMS bk $")).await;
            tokio::time::sleep(Duration::from_millis(150)).await;
            w.call(&a("XADD bk 5-1 f v")).await;
            let (v, _) = r.read(Duration::from_secs(10)).await.unwrap();
            step(v, false);
            // 2. `$` means entries after the last one at the call.
            r.send(&a("XREAD BLOCK 5000 STREAMS bk $")).await;
            tokio::time::sleep(Duration::from_millis(150)).await;
            w.call(&a("XADD bk 6-1 g w")).await;
            let (v, _) = r.read(Duration::from_secs(10)).await.unwrap();
            step(v, false);
            // 3. A timeout.
            let t0 = std::time::Instant::now();
            let (v, _) = r.call(&a("XREAD BLOCK 200 STREAMS bk $")).await;
            step(v, t0.elapsed() >= Duration::from_millis(180));
            // 4. XREADGROUP BLOCK >, served by an XADD to the second key.
            w.call(&a("XGROUP CREATE bk g $")).await;
            w.call(&a("XGROUP CREATE bk2 g $ MKSTREAM")).await;
            r.send(&a("XREADGROUP GROUP g c BLOCK 5000 STREAMS bk bk2 > >"))
                .await;
            tokio::time::sleep(Duration::from_millis(150)).await;
            w.call(&a("XADD bk2 7-1 h x")).await;
            let (v, _) = r.read(Duration::from_secs(10)).await.unwrap();
            step(v, false);
            let (v, _) = w.call(&a("XPENDING bk2 g")).await;
            step(v, false);
            // 5. A history read never blocks.
            let (v, _) = r
                .call(&a("XREADGROUP GROUP g c BLOCK 2000 STREAMS bk 0"))
                .await;
            step(v, false);
            // 6. Two readers on one key both get the entry.
            let mut r2 = Conn::open(target, login).await;
            r2.call(&a(&format!("HELLO {proto}"))).await;
            r.send(&a("XREAD BLOCK 5000 STREAMS bk 6-1")).await;
            r2.send(&a("XREAD BLOCK 5000 STREAMS bk 6-1")).await;
            tokio::time::sleep(Duration::from_millis(150)).await;
            w.call(&a("XADD bk 8-1 i y")).await;
            let (v, _) = r.read(Duration::from_secs(10)).await.unwrap();
            step(v, false);
            let (v, _) = r2.read(Duration::from_secs(10)).await.unwrap();
            step(v, false);
            // 7. A blocked group read whose key goes away.
            r.send(&a("XREADGROUP GROUP g c BLOCK 5000 STREAMS bk >"))
                .await;
            tokio::time::sleep(Duration::from_millis(150)).await;
            w.call(&a("DEL bk")).await;
            let (v, _) = r.read(Duration::from_secs(10)).await.unwrap();
            step(v, false);
            // 8. A blocked group read whose group is destroyed.
            r.send(&a("XREADGROUP GROUP g c BLOCK 5000 STREAMS bk2 >"))
                .await;
            tokio::time::sleep(Duration::from_millis(150)).await;
            w.call(&a("XGROUP DESTROY bk2 g")).await;
            let (v, _) = r.read(Duration::from_secs(10)).await.unwrap();
            step(v, false);
            // 9. XREAD + on an empty stream blocks until an entry arrives.
            w.call(&a("XADD bk3 1-1 a b")).await;
            w.call(&a("XDEL bk3 1-1")).await;
            r.send(&a("XREAD BLOCK 5000 STREAMS bk3 +")).await;
            tokio::time::sleep(Duration::from_millis(150)).await;
            w.call(&a("XADD bk3 2-1 c d")).await;
            let (v, _) = r.read(Duration::from_secs(10)).await.unwrap();
            step(v, false);
            results.push(out);
        }
        for (i, (x, y)) in results[0].iter().zip(&results[1]).enumerate() {
            t.commands += 1;
            if x == y {
                t.identical += 1;
            } else {
                t.bad.push(format!(
                    "RESP{proto} step {i}\n   sprig: {x:?}\n   redis: {y:?}"
                ));
            }
        }
    }
    report("blocking", &t);
    assert!(t.bad.is_empty(), "{} of {} differ", t.bad.len(), t.commands);
}

/// Approximate trimming (`~`) over hundreds of small entries: Redis drops
/// whole nodes of 100 entries.
#[ignore = "live: needs SPRIG_TEST_REDIS_ENGINE, SPRIG_TEST_REDIS_REF, SPRIG_TEST_STREAM_ROUNDS; tools/live/README.md"]
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn approximate_trims_match_redis() {
    let Some(mut p) = Pair::new().await else {
        eprintln!("SPRIG_TEST_REDIS_REF not set: skipped");
        panic!("live test run without its environment: see tools/live/README.md");
    };
    let mut t = Tally::default();
    let mut script: Vec<String> = Vec::new();
    for i in 1..=250 {
        script.push(format!("XADD s MAXLEN ~ 10 {i}-0 f v"));
        if i % 10 == 0 {
            script.push("XLEN s".into());
        }
    }
    script.push("XINFO STREAM s".into());
    for i in 1..=350 {
        script.push(format!("XADD u {i}-0 f v"));
    }
    script.extend(
        [
            "XDEL u 1-0 2-0 150-0 151-0",
            "XTRIM u MAXLEN ~ 300",
            "XTRIM u MAXLEN ~ 200",
            "XLEN u",
            "XTRIM u MAXLEN ~ 0 LIMIT 50",
            "XTRIM u MAXLEN ~ 0 LIMIT 150",
            "XLEN u",
            "XTRIM u MINID ~ 290",
            "XLEN u",
            "XTRIM u MINID ~ 301",
            "XLEN u",
            "XINFO STREAM u",
            "XTRIM u MAXLEN ~ 0",
            "XLEN u",
            "XINFO STREAM u",
        ]
        .map(String::from),
    );
    for i in 1..=120 {
        script.push(format!("XADD v MINID ~ {} {i}-0 f v", i / 2));
    }
    script.push("XLEN v".into());
    script.push("XRANGE v - + COUNT 3".into());
    for (n, l) in script.iter().enumerate() {
        p.one(&split(l), false, &mut t, &format!("step {n}:")).await;
    }
    report("approximate trims", &t);
    assert!(t.bad.is_empty(), "{} of {} differ", t.bad.len(), t.commands);
}
