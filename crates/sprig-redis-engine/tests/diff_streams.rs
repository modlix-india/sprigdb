/// A reply, every RESP type kept apart.
#[derive(Debug, Clone, PartialEq)]
enum V {
    Simple(String),
    Err(String),
    Int(i64),
    Bulk(Vec<u8>),
    NullBulk,
    NullArray,
    Null,
    Arr(Vec<V>),
    Map(Vec<(V, V)>),
    Set(Vec<V>),
    Push(Vec<V>),
    Double(String),
    Bool(bool),
    Big(String),
    Verbatim(Vec<u8>),
    /// A masked value.
    Mask(String),
}

fn line(b: &[u8], at: usize) -> Option<(&[u8], usize)> {
    let rest = b.get(at..)?;
    let p = rest.windows(2).position(|w| w == b"\r\n")?;
    Some((&rest[..p], at + p + 2))
}

/// One reply from `b[at..]`: it and where the next starts.
fn parse(b: &[u8], at: usize) -> Option<(V, usize)> {
    let kind = *b.get(at)?;
    let (l, next) = line(b, at + 1)?;
    let text = || String::from_utf8_lossy(l).into_owned();
    let num = || -> Option<i64> { std::str::from_utf8(l).ok()?.parse().ok() };
    let items = |n: i64, mut p: usize| -> Option<(Vec<V>, usize)> {
        let mut v = Vec::new();
        for _ in 0..n {
            let (x, q) = parse(b, p)?;
            v.push(x);
            p = q;
        }
        Some((v, p))
    };
    Some(match kind {
        b'+' => (V::Simple(text()), next),
        b'-' => (V::Err(text()), next),
        b':' => (V::Int(num()?), next),
        b'_' => (V::Null, next),
        b'#' => (V::Bool(l == b"t"), next),
        b',' => (V::Double(text()), next),
        b'(' => (V::Big(text()), next),
        b'$' | b'=' => {
            let n = num()?;
            if n < 0 {
                return Some((V::NullBulk, next));
            }
            let end = next + n as usize;
            let body = b.get(next..end)?.to_vec();
            b.get(end..end + 2)?;
            let v = if kind == b'$' {
                V::Bulk(body)
            } else {
                V::Verbatim(body)
            };
            (v, end + 2)
        }
        b'*' | b'~' | b'>' => {
            let n = num()?;
            if n < 0 {
                return Some((V::NullArray, next));
            }
            let (v, p) = items(n, next)?;
            (
                match kind {
                    b'*' => V::Arr(v),
                    b'~' => V::Set(v),
                    _ => V::Push(v),
                },
                p,
            )
        }
        b'%' => {
            let n = num()?;
            let (v, p) = items(n * 2, next)?;
            let mut it = v.into_iter();
            let mut m = Vec::new();
            while let (Some(k), Some(x)) = (it.next(), it.next()) {
                m.push((k, x));
            }
            (V::Map(m), p)
        }
        _ => return None,
    })
}

fn wire(args: &[Vec<u8>]) -> Vec<u8> {
    let mut v = format!("*{}\r\n", args.len()).into_bytes();
    for a in args {
        v.extend_from_slice(format!("${}\r\n", a.len()).as_bytes());
        v.extend_from_slice(a);
        v.extend_from_slice(b"\r\n");
    }
    v
}

/// A raw connection.
struct Conn {
    s: TcpStream,
    buf: Vec<u8>,
}

impl Conn {
    async fn open(addr: &str, login: Option<(&str, &str)>) -> Self {
        let s = TcpStream::connect(addr).await.unwrap();
        let mut c = Self { s, buf: Vec::new() };
        if let Some((u, p)) = login {
            let (r, _) = c.call(&[b"AUTH".to_vec(), u.into(), p.into()]).await;
            assert_eq!(r, V::Simple("OK".into()));
        }
        c
    }

    async fn send(&mut self, args: &[Vec<u8>]) {
        self.s.write_all(&wire(args)).await.unwrap();
    }

    /// The next reply and its bytes.
    async fn read(&mut self, wait: Duration) -> Option<(V, Vec<u8>)> {
        loop {
            if let Some((v, end)) = parse(&self.buf, 0) {
                let bytes: Vec<u8> = self.buf.drain(..end).collect();
                return Some((v, bytes));
            }
            let mut chunk = vec![0u8; 65536];
            let got = tokio::time::timeout(wait, self.s.read(&mut chunk))
                .await
                .ok()?
                .unwrap();
            assert!(got > 0, "connection closed");
            self.buf.extend_from_slice(&chunk[..got]);
        }
    }

    async fn call(&mut self, args: &[Vec<u8>]) -> (V, Vec<u8>) {
        self.send(args).await;
        self.read(Duration::from_secs(20)).await.expect("no reply")
    }
}

// ---------------------------------------------------------------------------
// Masking.

/// One side's generated IDs, in the order they appeared.
#[derive(Default)]
struct Masks {
    ids: HashMap<Vec<u8>, String>,
}

fn looks_like_id(b: &[u8]) -> bool {
    let s = std::str::from_utf8(b).unwrap_or("");
    let mut p = s.splitn(2, '-');
    let (Some(ms), Some(seq)) = (p.next(), p.next()) else {
        return false;
    };
    !ms.is_empty()
        && !seq.is_empty()
        && ms.bytes().all(|c| c.is_ascii_digit())
        && seq.bytes().all(|c| c.is_ascii_digit())
}

impl Masks {
    /// Records the ID an `XADD ... *` answered.
    fn learn(&mut self, cmd: &[Vec<u8>], r: &V) {
        if !cmd[0].eq_ignore_ascii_case(b"xadd") || !cmd.iter().any(|a| a == b"*") {
            return;
        }
        if let V::Bulk(id) = r {
            let n = self.ids.len();
            self.ids.entry(id.clone()).or_insert(format!("G{n}"));
        }
    }

    fn id(&self, b: &[u8]) -> Option<V> {
        // An ID generated by `*`, or one in the clock's range (`ms-*` and
        // `$` follow the clock too).
        if let Some(t) = self.ids.get(b) {
            return Some(V::Mask(t.clone()));
        }
        if looks_like_id(b) {
            let ms: u64 = std::str::from_utf8(b)
                .ok()?
                .split('-')
                .next()?
                .parse()
                .ok()?;
            if (1_000_000_000_000..10_000_000_000_000).contains(&ms) {
                return Some(V::Mask("CLOCK-ID".into()));
            }
        }
        None
    }
}

fn time_mask(i: i64) -> V {
    if i < 0 {
        V::Int(i)
    } else if i >= 1_000_000_000_000 {
        V::Mask("ABS".into())
    } else {
        V::Mask(format!("T{}s", i / 1000))
    }
}

/// `v` with generated IDs and clock readings masked; `masked` set when
/// anything was.
fn mask(m: &Masks, v: V, masked: &mut bool, time_key: bool) -> V {
    match v {
        V::Bulk(b) => match m.id(&b) {
            Some(x) => {
                *masked = true;
                x
            }
            None => V::Bulk(b),
        },
        V::Int(i) if time_key || i >= 1_000_000_000_000 => {
            *masked = true;
            time_mask(i)
        }
        V::Arr(a) => {
            // A pending row: [id, consumer, idle, count] (XPENDING) or
            // [id, consumer, delivery time, count] (XINFO FULL).
            let row = a.len() == 4
                && matches!(&a[0], V::Bulk(b) if looks_like_id(b))
                && matches!(&a[1], V::Bulk(_))
                && matches!(&a[2], V::Int(_))
                && matches!(&a[3], V::Int(_));
            let flat_time = flat_map_keys(&a);
            V::Arr(
                a.into_iter()
                    .enumerate()
                    .map(|(i, x)| {
                        let t = (row && i == 2) || flat_time.contains(&i);
                        mask(m, x, masked, t)
                    })
                    .collect(),
            )
        }
        V::Map(kv) => V::Map(
            kv.into_iter()
                .map(|(k, x)| {
                    let t = matches!(&k, V::Bulk(b) if is_time_key(b));
                    (mask(m, k, masked, false), mask(m, x, masked, t))
                })
                .collect(),
        ),
        V::Set(a) => V::Set(a.into_iter().map(|x| mask(m, x, masked, false)).collect()),
        V::Push(a) => V::Push(a.into_iter().map(|x| mask(m, x, masked, false)).collect()),
        o => o,
    }
}

fn is_time_key(b: &[u8]) -> bool {
    matches!(b, b"idle" | b"inactive" | b"seen-time" | b"active-time")
}

/// In a RESP2 map as a flat array, the indexes of values under time keys.
fn flat_map_keys(a: &[V]) -> Vec<usize> {
    let mut out = Vec::new();
    for (i, x) in a.iter().enumerate() {
        if let V::Bulk(b) = x
            && is_time_key(b)
            && i % 2 == 0
        {
            out.push(i + 1);
        }
    }
    out
}

