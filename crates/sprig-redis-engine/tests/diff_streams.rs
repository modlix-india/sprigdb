//! Differential tests of Redis streams on engine databases against a
//! reference Redis, reply bytes compared over raw connections, in RESP2
//! and RESP3.
//!
//! - `SPRIG_TEST_REDIS_REF`: a reference Redis 7.4, such as
//!   `127.0.0.1:62479`. Unset: the tests are skipped.
//! - `SPRIG_TEST_REDIS_ENGINE`: a SprigDB node's Redis listener whose
//!   tenant is on the engine (`redis://user:pw@127.0.0.1:61480`). When
//!   unset, the tests start the Redis front end in process with every
//!   database on the engine (RocksDB with real syncs).
//!
//! What differs by nature is masked on both sides before comparing: IDs
//! generated by `*` (each becomes `G<n>` in the order they appear), and
//! clock readings (idle times as whole seconds, instants as `ABS`).
//! Everything else must be byte-identical. Both servers are flushed first;
//! never point these at a server holding data.

